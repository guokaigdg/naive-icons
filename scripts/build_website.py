def to_pascal(name: str) -> str:
    return ''.join(p.capitalize() for p in re.split(r'[-_]', name)) + 'Icon'


def compact_svg(raw: str) -> str:
    """压缩 SVG：去掉换行与多余空格，保留内容结构"""
    raw = raw.strip()
    raw = re.sub(r'>\s+<', '><', raw)
    raw = re.sub(r'\s{2,}', ' ', raw)
    return raw


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    files = sorted(SVG_DIR.glob('*.svg'))
    if not files:
        raise SystemExit(f'未找到 SVG 文件：{SVG_DIR}')

    icons = []
    unassigned = []
    for f in files:
        name = f.stem
        cat = ICON_CATEGORY.get(name)
        if not cat:
            unassigned.append(name)
            cat = 'interface'
        icons.append({
            'id': name,
            'zh': ZH_NAMES.get(name, name),
            'cat': cat,
            'comp': to_pascal(name),
            'svg': compact_svg(f.read_text(encoding='utf-8')),
        })

    icons.sort(key=lambda x: (list(CATEGORY_MAP).index(x['cat']), x['id']))

    payload = {
        'version': '1.0.0',
        'total': len(icons),
        'categories': [{'id': i, 'label': l} for i, l in CATEGORIES],
        'icons': icons,
    }

    js = (
        '/* Naive Icons — 图标数据（由 scripts/build_website.py 自动生成，请勿手改） */\n'
        'window.NAIVE_ICONS = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n'
    )
    OUT_FILE.write_text(js, encoding='utf-8')

    html_path = ROOT / 'website' / 'index.html'
    if html_path.is_file():
        html = html_path.read_text(encoding='utf-8')
        before = html
        total = len(icons)
        html = re.sub(r'(浏览 )\d+( 个图标)', rf'\g<1>{total}\g<2>', html)
        html = re.sub(r'(共 )\d+( 个图标)', rf'\g<1>{total}\g<2>', html)
        ver = json.loads((ROOT / 'package.json').read_text(encoding='utf-8'))['version']
        html = re.sub(r'<b>v\d+\.\d+\.\d+</b>', f'<b>v{ver}</b>', html)
        html = re.sub(r'(Naive Icons )v\d+\.\d+\.\d+', rf'\g<1>v{ver}', html)
        if html != before:
            html_path.write_text(html, encoding='utf-8')
            print(f'已同步 website/index.html：图标总数 {total}、版本 v{ver}')

    print(f'图标总数: {len(icons)}')
    print(f'输出文件: {OUT_FILE}')
    print(f'文件大小: {OUT_FILE.stat().st_size / 1024:.1f} KB')
    for cid, label in CATEGORIES:
        n = sum(1 for i in icons if i['cat'] == cid)
        print(f'  {label:<10s} {n}')
    if unassigned:
        print('未分类（已归入界面基础）:', ', '.join(unassigned))


if __name__ == '__main__':
    main()
